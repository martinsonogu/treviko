import type {WorkoutEvidence} from './workout-evidence';
import type {ConversationContext} from './context';
import { z } from 'zod';
import { equipmentOptions, experienceLevels, muscleGroups } from '../training/types';

const shortText = z.string().trim().min(1).max(500);
export const profileSchema = z.object({
  goals: shortText.optional(),
  experience: z.enum(experienceLevels).optional(),
  equipment: z.array(z.enum(equipmentOptions)).max(equipmentOptions.length).refine(items => new Set(items).size === items.length, 'Duplicate equipment').optional(),
  trainingFrequency: z.number().int().min(1).max(7).optional(),
  dietaryPreferences: shortText.optional(),
  allergies: shortText.optional(),
  foodBudget: shortText.optional(),
  existingWorkoutPlan: z.string().trim().min(1).max(1500).optional(),
  recentTrainingHistory: z.string().trim().min(1).max(1500).optional(),
}).strict();
export const coachRequestSchema = z.object({
  message: z.string().trim().min(1).max(2000),
  // Client-supplied history is context only, never authenticated assistant instructions.
  history: z.array(z.object({ role: z.enum(['user', 'assistant']), content: z.string().trim().min(1).max(4000) }).strict()).max(10).default([]),
  profile: profileSchema.default({}),
}).strict().refine(input => input.message.length + input.history.reduce((sum, entry) => sum + entry.content.length, 0) <= 12000, 'Conversation context is too long');
export type CoachInput = z.infer<typeof coachRequestSchema> & {workoutEvidence?:WorkoutEvidence;savedPlanContext?:{trainingGoal?:string|null;nutritionGoal?:string|null;goal?:string;scope?:string;version:number;training:{weekday:number;name:string;exerciseIds:string[]}[];meals:{slot:number;name:string}[];sessionMinutes:number}|null;conversationContext?:ConversationContext;providedPreferences?:CoachProfile;exerciseContext?:{availability:string;guidance:string|null}};
export type CoachProfile = z.infer<typeof profileSchema>;

export const safetyKinds = ['none', 'emergency', 'injury', 'medical', 'eating_disorder', 'dangerous', 'supplements', 'minor'] as const;
export type SafetyKind = typeof safetyKinds[number];
export const conversationCategories=['fitness','nutrition','fitness_profile','greeting','coaching_followup','ambiguous','unrelated','safety_sensitive'] as const;
export type ConversationCategory=typeof conversationCategories[number];
export const scopeSchema = z.object({
  category:z.enum(conversationCategories),
  outcome: z.enum(['allowed', 'unrelated', 'ambiguous', 'safety_sensitive']),
  topic: z.enum(['fitness', 'nutrition', 'mixed', 'other']),
  safety: z.enum(safetyKinds),
  injection: z.boolean(),
  needsExercises: z.boolean(),
  muscles: z.array(z.enum(muscleGroups)).max(3),
}).strict();
export type ScopeDecision = z.infer<typeof scopeSchema>;
export const draftSchema = z.object({ message: z.string().min(1).max(4000), exerciseIds: z.array(z.string().min(1).max(80)).max(4) }).strict();
export type CoachDraft = z.infer<typeof draftSchema>;
export const reviewSchema = z.object({ inScope: z.boolean(), safe: z.boolean(), groundedExercises: z.boolean(), honestNutrition: z.boolean(), private: z.boolean() }).strict();
export type CoachReview = z.infer<typeof reviewSchema>;
export const coachResponseSchema = z.object({
  message: z.string().min(1).max(5000),
  category: z.enum(['fitness', 'nutrition', 'mixed', 'fitness_profile', 'greeting', 'coaching_followup', 'unrelated', 'ambiguous', 'safety', 'configuration', 'error']),
  status: z.enum(['ok', 'declined', 'clarification', 'safety', 'unavailable', 'error', 'rate_limited']),
  mode: z.enum(['live', 'policy', 'unavailable']),
  exerciseIds: z.array(z.string()).max(4),
  exerciseSlugs: z.array(z.string()).max(4),
  // Authoritative library records are attached after validation; never generated by the model.
  nutritionData: z.literal('not_connected'),
  code: z.string().optional(),
}).strict();
export type CoachResponse = z.infer<typeof coachResponseSchema>;
