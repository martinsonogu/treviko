export function getApprovedIllustration(
  exerciseId: string,
  registry: Record<string, ApprovedIllustration> = approvedIllustrations,
) {
  if (!Object.hasOwn(registry, exerciseId) || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(exerciseId))
    return null;
  const asset = registry[exerciseId];
  const review = asset?.review;
  if (
    !asset ||
    !Number.isInteger(asset.revision) ||
    asset.revision < 1 ||
    asset.src !== `/exercises/v${asset.revision}/${exerciseId}.webp` ||
    !Number.isInteger(asset.width) ||
    asset.width <= 0 ||
    !Number.isInteger(asset.height) ||
    asset.height <= 0 ||
    !asset.alt?.trim() ||
    !/^[a-f0-9]{64}$/.test(asset.sha256) ||
    review?.anatomy !== "approved" ||
    review?.visual !== "approved" ||
    review?.rights !== "approved" ||
    !review.reviewer?.trim() ||
    !review.license?.trim() ||
    !review.provenance?.trim() ||
    !/^\d{4}-\d{2}-\d{2}$/.test(review.reviewedAt) ||
    !Number.isFinite(Date.parse(review.reviewedAt))
  )
    return null;
  return asset;
}
